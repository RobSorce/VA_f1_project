"""Replay frames (FastF1Extractor.extract_race_frames): a car that retires leaves the
frames after its last sample in motion instead of staying frozen on track, and the
categorical channels (lap, gear, DRS code, compound, tyre life) hold the value of the
previous real sample instead of being interpolated between two codes.

A synthetic FastF1-like session checks the rule sample by sample; the cached frames of
2024 R3 (VER out on lap 4, HAM on lap 16, RUS in the barrier on lap 57), regenerated by
scripts/regenerate_frames.py, check it on a real race."""
import json

import numpy as np
import pandas as pd
import pytest

from conftest import CACHE_DIR, load_cached_session

T0 = 1000.0  # session time of the first sample
STEP = 0.25  # telemetry spacing (s)


class FakeLap(dict):
    tel = {}

    def get_telemetry(self):
        return FakeLap.tel[(self['DriverNumber'], self['LapNumber'])]


class FakeLaps(pd.DataFrame):
    @property
    def _constructor(self):
        return FakeLaps

    def pick_drivers(self, num):
        return self[self['DriverNumber'] == num]

    def iterlaps(self):
        for i, r in self.iterrows():
            yield i, FakeLap(r.to_dict())


def telemetry(t, x, speed, gear, drs):
    t = np.asarray(t, dtype=float)
    return pd.DataFrame({
        'SessionTime': pd.to_timedelta(T0 + t, unit='s'), 'X': x, 'Y': np.zeros_like(t),
        'Speed': speed, 'nGear': gear, 'DRS': drs, 'Throttle': np.full_like(t, 50.0),
        'Brake': np.zeros_like(t),
    })


def fake_session():
    """Car 1 (AAA) runs 3 laps of 20 s and takes the flag at t=60: DRS 0 -> 8 at t=25.25
    -> 12 at 30.25 -> 14 at 35.25, gear 3/5/7 by 5 s, SOFT laps 1-2 and HARD lap 3
    (first sample at 40.6, after a gap), and nGear readings of 42 at t=12.0-12.5 (the
    feed sends such values for a car standing in the pit lane). Car 2 (BBB) stops on
    lap 2 at t=28 and keeps streaming a parked position at speed 0 until t=50. Car 3
    (CCC) never moves (out before the start) but streams samples until t=20."""
    tel = {}
    for lap, (a, b) in enumerate([(0, 20), (20, 40), (40.6, 60)], start=1):
        t = np.arange(a, b + 1e-9, STEP)
        drs = np.select([t >= 35.25, t >= 30.25, t >= 25.25], [14, 12, 8], 0) if lap == 2 else np.zeros_like(t)
        gear = np.array([3, 5, 7])[(t // 5).astype(int) % 3]
        gear[(t >= 12.0) & (t <= 12.5)] = 42
        tel[('1', lap)] = telemetry(t, t * 10, np.full_like(t, 200.0), gear, drs)
    for lap, (a, b) in enumerate([(0, 20), (20, 50)], start=1):
        t = np.arange(a, b + 1e-9, STEP)
        moving = t <= 28
        tel[('2', lap)] = telemetry(t, np.where(moving, t * 9, 28 * 9), np.where(moving, 150.0, 0.0),
                                    np.where(moving, 4, 0), np.zeros_like(t))
    t = np.arange(0, 20 + 1e-9, STEP)
    tel[('3', 1)] = telemetry(t, np.full_like(t, -50.0), np.zeros_like(t), np.zeros_like(t), np.zeros_like(t))
    FakeLap.tel = tel
    laps = FakeLaps({
        'DriverNumber': ['1', '1', '1', '2', '2', '3'],
        'LapNumber': [1, 2, 3, 1, 2, 1],
        'Time': pd.to_timedelta([T0 + 20, T0 + 40, T0 + 60, T0 + 20, np.nan, np.nan], unit='s'),
        'Compound': ['SOFT', 'SOFT', 'HARD', 'MEDIUM', 'MEDIUM', 'SOFT'],
        'TyreLife': [1.0, 2.0, 1.0, 5.0, 6.0, 1.0],
    })
    info = {'1': {'Abbreviation': 'AAA', 'TeamColor': '111111'}, '2': {'Abbreviation': 'BBB', 'TeamColor': '222222'},
            '3': {'Abbreviation': 'CCC', 'TeamColor': '333333'}}

    class Session:
        drivers = ['1', '2', '3']

        def get_driver(self, num):
            return info[num]

    s = Session()
    s.laps = laps
    return s


@pytest.fixture(scope='module')
def frames():
    from data.extractors.fastf1_extractor import FastF1Extractor

    return FastF1Extractor().extract_race_frames(fake_session())


def test_retired_car_leaves_the_frames_after_its_last_sample_in_motion(frames):
    assert frames['frames_format'] == 2
    assert frames['retired_at'] == {'BBB': 28.0, 'CCC': 0.0}
    with_b = [f['t'] for f in frames['frames'] if 'BBB' in f['drivers']]
    assert max(with_b) == 28.0 and with_b == [f['t'] for f in frames['frames'] if f['t'] <= 28.0]
    # a car never in motion is not drawn after its first sample
    assert [f['t'] for f in frames['frames'] if 'CCC' in f['drivers']] == [0.0]
    # the finisher stays to the end of the replay
    assert all('AAA' in f['drivers'] for f in frames['frames'])
    assert frames['frames'][-1]['t'] == pytest.approx(59.6)


def at(frames, t, code='AAA'):
    return next(f['drivers'][code] for f in frames['frames'] if f['t'] == t)


def test_categorical_channels_hold_the_previous_sample(frames):
    seen = {k: {f['drivers']['AAA'][k] for f in frames['frames']} for k in ('drs', 'gear', 'tyre', 'lap')}
    assert seen == {'drs': {0, 8, 12, 14}, 'gear': {3, 5, 7}, 'tyre': {1, 3}, 'lap': {1, 2, 3}}
    # linear interpolation gave DRS 6 at t=25.2 (0 at 25.0, 8 at 25.25) and MEDIUM (2)
    # at t=40.4 (SOFT at 40.0, HARD at 40.6): the previous sample holds instead
    assert at(frames, 25.2)['drs'] == 0 and at(frames, 25.6)['drs'] == 8
    assert at(frames, 40.4)['tyre'] == 1 and at(frames, 40.8)['tyre'] == 3
    assert at(frames, 19.6)['lap'] == 1 and at(frames, 20.4)['lap'] == 2
    assert at(frames, 14.8)['gear'] == 7 and at(frames, 15.2)['gear'] == 3  # interpolated: 6
    assert at(frames, 12.4)['gear'] == 7  # the 42 readings skipped: the previous valid gear
    assert {f['drivers']['AAA']['tyre_life'] for f in frames['frames']} == {1.0, 2.0}
    # continuous channels are still interpolated
    assert at(frames, 25.2)['x'] == pytest.approx(252.0)


def regenerated_frames(year, rnd):
    path = CACHE_DIR / f'frames_{year}_{rnd}_R.json'
    if not path.exists():
        pytest.skip(f'processed cache missing: {path.name}')
    data = json.loads(path.read_text())
    if data.get('frames_format') != 2:
        pytest.skip(f'{path.name} predates frames_format 2: run scripts/regenerate_frames.py')
    return data


COMPOUND_INT = {'SOFT': 1, 'MEDIUM': 2, 'HARD': 3, 'INTERMEDIATE': 4, 'WET': 5}
DRS_CODES = {0, 1, 2, 3, 8, 9, 10, 12, 14}  # FastF1 car data DRS values


@pytest.mark.parametrize('year, rnd', [(2024, 3), (2024, 5)])
def test_cached_race_frames_follow_the_rule(year, rnd):
    data = regenerated_frames(year, rnd)
    session = load_cached_session(year, rnd)
    laps = session['lap_times']
    t0 = min(r['LapStartTime'] for r in laps if r['LapNumber'] == 1 and r.get('LapStartTime') is not None)
    retired = {r['Abbreviation'] for r in session['race_results']
               if r['Status'] not in ('Finished', 'Lapped') and not str(r['Status']).startswith('+')}

    # every car leaving early is classified as retired, and leaves where its last lap ends
    # (FastF1's lap Time, the generated one for a car stopping on track) within 3 s
    assert set(data['retired_at']) <= retired
    for code, t_ret in data['retired_at'].items():
        last_end = max(r['Time'] for r in laps if r['Driver'] == code and r.get('Time') is not None)
        assert abs(t_ret - (last_end - t0)) < 3.0, (code, t_ret, last_end - t0)
        present = [f['t'] for f in data['frames'] if code in f['drivers']]
        assert present[-1] <= t_ret < present[-1] + 0.4 + 1e-6

    used = {}
    for r in laps:
        used.setdefault(r['Driver'], {0}).add(COMPOUND_INT.get(str(r.get('Compound')).upper(), 0))
    first_seen = {}
    for i, f in enumerate(data['frames']):
        for code, d in f['drivers'].items():
            first_seen.setdefault(code, i)
            assert d['drs'] in DRS_CODES, (code, f['t'], d['drs'])
            assert isinstance(d['gear'], int) and 0 <= d['gear'] <= 8
            assert d['tyre'] in used[code], (code, f['t'], d['tyre'])
            assert isinstance(d['lap'], int) and d['tyre_life'] == int(d['tyre_life'])
    # the cars that are not retired are in every frame from their first one to the end
    for code, i0 in first_seen.items():
        if code not in data['retired_at']:
            assert all(code in f['drivers'] for f in data['frames'][i0:]), code


def test_2024_r3_verstappen_leaves_at_his_retirement():
    data = regenerated_frames(2024, 3)
    session = load_cached_session(2024, 3)
    ver = [r for r in session['lap_times'] if r['Driver'] == 'VER']
    t0 = min(r['LapStartTime'] for r in session['lap_times'] if r['LapNumber'] == 1)
    assert max(r['LapNumber'] for r in ver) == 4  # brake failure: into the garage after lap 4
    pit_in = max(r['Time'] for r in ver) - t0
    assert data['retired_at']['VER'] == pytest.approx(pit_in, abs=0.5)
    assert any('VER' in f['drivers'] for f in data['frames'] if f['t'] > pit_in - 1.0)
    assert not any('VER' in f['drivers'] for f in data['frames'] if f['t'] > pit_in + 0.5)
