const LETTERS = 'abcdefghijklmnopqrstuvwxyz'.split('');
const DIGITS = '1234567890'.split('');
const SYMBOLS = ['?', '/', '<', '>', '[', ']', ' ', 'Escape', 'ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown', 'Home', 'End'];

const KEY_NAME = { ' ': 'Space', Escape: 'Esc', ArrowLeft: '←', ArrowRight: '→', ArrowUp: '↑', ArrowDown: '↓' };

/** Readable name of a combination: 'Shift+P', 'Ctrl+K', 'Ctrl+Alt+D', 'Space'. */
export function comboName({ key, shiftKey, ctrlKey, metaKey, altKey }) {
  const k = KEY_NAME[key] || (key.length === 1 ? key.toUpperCase() : key);
  const mods = [];
  if (ctrlKey) mods.push('Ctrl');
  if (metaKey) mods.push('Cmd');
  if (altKey) mods.push('Alt');
  if (shiftKey && /^[a-z]$/i.test(key)) mods.push('Shift');
  return [...mods, k].join('+');
}

function combos() {
  const out = [];
  for (const k of DIGITS) out.push({ key: k });
  for (const k of LETTERS) {
    out.push({ key: k });
    out.push({ key: k.toUpperCase(), shiftKey: true });
  }
  for (const k of SYMBOLS) out.push({ key: k });
  for (const mod of ['ctrlKey', 'metaKey']) {
    for (const k of [...LETTERS, 'ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown']) out.push({ key: k, [mod]: true });
    out.push({ key: 'd', [mod]: true, altKey: true });
  }
  out.push({ key: 'a', altKey: true });
  return out.map((c) => ({ shiftKey: false, ctrlKey: false, metaKey: false, altKey: false, ...c }));
}

// ── The recording store and the stub window ────────────────────────────

/**
 * Install the real handler on a stub window and return a probe: probe(combo,
 * state, activeElement) sends one keydown and returns what the handler did.
 * restore() puts the globals and the store back.
 */
export function installHandler() {
  const initial = useF1Store.getState();
  const data = {};
  for (const [k, v] of Object.entries(initial)) if (typeof v !== 'function') data[k] = v;
  const saved = {
    window: globalThis.window, document: globalThis.document, CustomEvent: globalThis.CustomEvent,
  };
  const listeners = [];
  const dispatched = [];
  globalThis.window = {
    addEventListener: (type, fn) => listeners.push({ type, fn }),
    removeEventListener: () => {},
    dispatchEvent: (ev) => { dispatched.push(ev.type); return true; },
  };
  globalThis.document = { activeElement: null, body: { tagName: 'BODY' } };
  globalThis.CustomEvent = class CustomEvent { constructor(type, init) { this.type = type; this.detail = init?.detail; } };

  // React runs a hook's effect at commit; outside a render the effect is run
  // at once, which is all useKeyboardShortcuts does (it adds its listener)
  const internals = React.__SECRET_INTERNALS_DO_NOT_USE_OR_YOU_WILL_BE_FIRED;
  const prevDispatcher = internals.ReactCurrentDispatcher.current;
  internals.ReactCurrentDispatcher.current = { useEffect: (fn) => { fn(); } };
  try {
    useKeyboardShortcuts();
  } finally {
    internals.ReactCurrentDispatcher.current = prevDispatcher;
  }
  const keydown = listeners.filter((l) => l.type === 'keydown');
  if (keydown.length !== 1) throw new Error(`expected one keydown listener, found ${keydown.length}`);
  const handler = keydown[0].fn;

  const recorder = (calls) => {
    const rec = {};
    for (const [k, v] of Object.entries(initial)) {
      if (typeof v === 'function') rec[k] = (...args) => { calls.push({ name: k, args }); };
    }
    return rec;
  };

  /** Run fn on the recording store in `state`; what it called and set. */
  function record(fn, state = {}, activeElement = null) {
    const calls = [];
    useF1Store.setState({ ...data, ...recorder(calls), ...REPLAY_STATE, ...state }, true);
    const before = useF1Store.getState();
    dispatched.length = 0;
    let blurred = false;
    globalThis.document.activeElement = activeElement
      ? { ...activeElement, blur: () => { blurred = true; } }
      : null;
    fn();
    const after = useF1Store.getState();
    const set = {};
    for (const f of DIRECT_FIELDS) if (after[f] !== before[f]) set[f] = after[f];
    return { calls, events: [...dispatched], set, blurred, state };
  }

  function probe(combo, state = {}, activeElement = null) {
    let prevented = false;
    let stopped = false;
    const ev = {
      ...combo,
      preventDefault: () => { prevented = true; },
      stopPropagation: () => { stopped = true; },
      getModifierState: () => false,
    };
    const r = record(() => handler(ev), state, activeElement);
    return { ...r, prevented, stopped };
  }

  function restore() {
    useF1Store.setState(initial, true);
    for (const [k, v] of Object.entries(saved)) {
      if (v === undefined) delete globalThis[k]; else globalThis[k] = v;
    }
  }

  return { probe, record, restore };
}

