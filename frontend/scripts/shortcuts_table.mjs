#!/usr/bin/env node
/**
 * Keyboard shortcuts of the dashboard, read from the code by running it.
 *
 * The global key handler (src/hooks/useKeyboardShortcuts.js) is installed on
 * a stub window and every key combination below is sent to it, on a store
 * whose actions only record their calls: what a key does is what the handler
 * calls, with the store state of a replay (a focus driver, an open window, a
 * compare pair). The handler's conditions (a field in focus, the cheatsheet
 * or the palette open, a season without DRS, ...) are probed the same way.
 * The keys a view handles itself are read from their modules: [ and ] of
 * the Circle of Doom (pitInLapsKeyStep, called with each modifier) and / of
 * the command bar (CommandBar.jsx).
 *
 * Then the two lists shown to the user are compared with the handler: the
 * cheatsheet (ShortcutCheatsheet.jsx SHORTCUT_SECTIONS, read from the
 * source) and the shortcut labels of the command palette
 * (commandRegistry.js createCommandRegistry: each command's action is run on
 * the same recording store, and its calls are compared with the handler's
 * for the key on its label).
 *
 * Usage (from frontend/):
 *   npx vite-node scripts/shortcuts_table.mjs              print the markdown, write docs/evidence/shortcuts_table.txt
 *   npx vite-node scripts/shortcuts_table.mjs --out FILE   write FILE instead
 *   npx vite-node scripts/shortcuts_table.mjs --write      also replace the generated block of docs/SHORTCUTS.md
 *
 * __tests__/shortcuts.doc.test.js checks that the block in docs/SHORTCUTS.md
 * equals this script's output.
 */
