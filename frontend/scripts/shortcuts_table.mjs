const IGNORED_CALLS = new Set(['closeCommandPalette']);

/** One recorded run in words ('' = the key does nothing). */
export function describe(r) {
  const parts = [];
  const st = { ...REPLAY_STATE, ...(r.state || {}) };
  for (const c of r.calls) {
    if (IGNORED_CALLS.has(c.name)) continue;
    const f = ACTION_TEXT[c.name];
    if (!f) {
      parts.push(`${c.name}(${c.args.map((a) => JSON.stringify(a)).join(', ')})`);
      continue;
    }
    // the state goes after the call's own arguments
    const args = [...c.args];
    while (args.length < f.length - 1) args.push(undefined);
    parts.push(f(...args, st));
  }
  for (const e of r.events) parts.push(`dispatch the window event "${e}"`);
  if (r.set?.commandPaletteOpen === true) {
    parts.push(r.set._paletteInitialCommand
      ? `open the command palette on "${r.set._paletteInitialCommand}"` : 'open the command palette');
  }
  if (r.blurred) parts.push('take the focus off the element that has it');
  return parts.join('; ');
}

/** What a run did, comparable between the handler and a palette action. */
function effectKey(r) {
  const norm = { openCheatsheet: 'toggleCheatsheet' };
  return JSON.stringify([
    r.calls.filter((c) => !IGNORED_CALLS.has(c.name)).map((c) => [norm[c.name] || c.name, c.args]),
    r.events,
    r.set?.commandPaletteOpen ? r.set._paletteInitialCommand || true : null,
  ]);
}

// ── The cheatsheet and the palette, as written ─────────────────────────

/** SHORTCUT_SECTIONS of ShortcutCheatsheet.jsx, evaluated (Ctrl as modKey). */
export function cheatsheetSections(src = fs.readFileSync(path.join(SRC, 'components/ShortcutCheatsheet/ShortcutCheatsheet.jsx'), 'utf8')) {
  const start = src.indexOf('const SHORTCUT_SECTIONS = ');
  const end = src.indexOf('\n];', start);
  if (start < 0 || end < 0) throw new Error('SHORTCUT_SECTIONS not found');
  const literal = src.slice(start + 'const SHORTCUT_SECTIONS = '.length, end + 2);
  // eslint-disable-next-line no-new-func
  return new Function('modKey', 'FIRST_SEASON_WITHOUT_DRS', `return ${literal};`)('Ctrl', FIRST_SEASON_WITHOUT_DRS);
}

const ARROW_KEY = { '←': 'ArrowLeft', '→': 'ArrowRight', '↑': 'ArrowUp', '↓': 'ArrowDown' };
const NAMED = { Space: ' ', Esc: 'Escape', Home: 'Home', End: 'End' };

/** A key label as the cheatsheet or the palette writes it -> the combination. */
export function comboOfLabel(label) {
  const base = { shiftKey: false, ctrlKey: false, metaKey: false, altKey: false };
  let s = String(label).trim();
  if (s.startsWith('⇧')) {
    const k = s.slice(1).trim();
    return { ...base, key: k.toUpperCase(), shiftKey: true };
  }
  if (/^(Ctrl|⌘)\+/.test(s)) {
    const parts = s.split('+');
    const k = parts[parts.length - 1];
    const alt = parts.includes('Alt');
    return { ...base, key: ARROW_KEY[k] || k.toLowerCase(), ctrlKey: true, altKey: alt };
  }
  if (NAMED[s]) return { ...base, key: NAMED[s] };
  if (ARROW_KEY[s]) return { ...base, key: ARROW_KEY[s] };
  if (/^[A-Z]$/.test(s)) return { ...base, key: s.toLowerCase() };
  return { ...base, key: s };
}

/** The combinations of one cheatsheet row: ['⇧', 'R'] is Shift+R, ['←', '→'] two keys. */
function cheatsheetCombos(keys) {
  if (keys[0] === '⇧') return [comboOfLabel(`⇧${keys[1]}`)];
  return keys.map(comboOfLabel);
}

// ── The tables ─────────────────────────────────────────────────────────

const code = (s) => `\`${s.replace(/`/g, '\\`')}\``;

/** Every result, computed once: { rows, conditions, local, cheatsheet, palette }. */
export function shortcutsReport() {
  const h = installHandler();
  try {
    // 1. every combination in the replay state
    const byEffect = new Map();
    for (const c of combos()) {
      const text = describe(h.probe(c));
      if (!text) continue;
      const name = comboName(c);
      if (!byEffect.has(text)) byEffect.set(text, []);
      byEffect.get(text).push(name);
    }
    const rows = [...byEffect.entries()].map(([effect, names]) => ({ keys: names, effect }));

    // 2. the conditions of the handler
    const k = (key, mods = {}) => ({ shiftKey: false, ctrlKey: false, metaKey: false, altKey: false, key, ...mods });
    const input = { tagName: 'INPUT' };
    const cond = (name, combo, state, el, note) => ({ name, when: note, effect: describe(h.probe(combo, state, el)) || 'nothing' });
    // Esc with two transient elements open (utils/escapeStack.js), a menu and
    // then a popover over it: what closes, and whether the layout stays
    const escStack = () => {
      const closed = [];
      const removes = [openEscapeLayer(() => { closed.push('menu'); }), openEscapeLayer(() => { closed.push('popover'); })];
      const r = h.probe(k('Escape'));
      removes.forEach((remove) => remove());
      const rest = describe(r);
      return {
        name: 'Esc',
        when: 'a menu, popover, dropdown, the help panel, the cheatsheet or the command bar list is open (here a menu, then a popover over it)',
        effect: `close ${closed.length === 1 && closed[0] === 'popover' ? 'the one opened last only (the popover)' : closed.join(', ') || 'nothing'}${rest ? `; ${rest}` : '; the windows and the docked layout stay'}${r.stopped ? '; the key goes no further' : ''}`,
      };
    };
    const conditions = [
      escStack(),
      cond('Esc', k('Escape'), { cheatsheetOpen: true }, null, 'the cheatsheet is open'),
      cond('Esc', k('Escape'), {}, null, 'a floating window or a docked layout is open, no menu, popover, dropdown, help or cheatsheet open'),
      cond('Esc', k('Escape'), { openOverlays: [], dockedLayout: null }, { tagName: 'BUTTON' }, 'no window open, a control has the focus'),
      cond('P', k('p'), { activeTab: 'pitwall' }, null, 'the Pit Wall is on screen'),
      cond('P', k('p'), {}, null, 'any other view is on screen'),
      cond('F', k('f'), { highlightedDriver: 'LEC' }, null, 'the driver under the pointer is the focus driver'),
      cond('F', k('f'), { focusDriver: null, highlightedDriver: null }, null, 'no focus driver, no driver under the pointer, LEC and SAI selected'),
      cond('F', k('f'), { focusDriver: null, highlightedDriver: null, selectedDrivers: [] }, null, 'no driver under the pointer and none selected'),
      cond('Shift+P', k('P', { shiftKey: true }), { focusDriver: null, highlightedDriver: null, selectedDrivers: ['SAI'] }, null, 'no focus driver, SAI selected'),
      cond('Shift+P', k('P', { shiftKey: true }), { currentLap: 1 }, null, 'the replay on lap 1 (no completed lap to forecast from)'),
      cond('Shift+D', k('D', { shiftKey: true }), { loadedYear: FIRST_SEASON_WITHOUT_DRS }, null, `a ${FIRST_SEASON_WITHOUT_DRS} session (no DRS)`),
      cond('Shift+G', k('G', { shiftKey: true }), { compareMode: false, compareDrivers: [] }, null, 'no compare pair (compare mode off or fewer than 2 drivers)'),
      cond('→', k('ArrowRight'), { currentLap: 53 }, null, 'on the last lap of a lap-mode replay'),
      cond('Ctrl+↓', k('ArrowDown', { ctrlKey: true }), { overlayTiles: {} }, null, 'the active window is not tiled'),
      cond('Ctrl+K', k('k', { ctrlKey: true }), { commandPaletteOpen: true }, null, 'the command palette is open'),
      cond('any other key', k('s'), { commandPaletteOpen: true }, null, 'the command palette is open (the palette handles the keys)'),
      cond('?', k('?'), { cheatsheetOpen: true }, null, 'the cheatsheet is open'),
      cond('Ctrl+K', k('k', { ctrlKey: true }), { cheatsheetOpen: true }, null, 'the cheatsheet is open'),
      cond('any key but Esc, ? and the Ctrl/Cmd combinations', k('s'), { cheatsheetOpen: true }, null, 'the cheatsheet is open'),
      cond('Esc', k('Escape'), {}, input, 'a text field has the focus and a window is open'),
      cond('any key but Esc and the Ctrl/Cmd combinations', k('s'), {}, input, 'a text field has the focus (input, textarea, select, editable)'),
      cond('Alt + any key but Ctrl/Cmd+Alt+D', k('s', { altKey: true }), {}, null, 'Alt is held'),
    ];
    // the playback speeds: '<' from 1x until it stops (the slowest), then
    // '>' from there until it stops; and both keys from 3x, a speed off the list
    const speedAfter = (key, sp) => h.probe(k(key), { playSpeed: sp }).calls.find((c) => c.name === 'setPlaySpeed')?.args[0] ?? null;
    let slowest = 1;
    for (let i = 0, sp = speedAfter('<', 1); sp != null && i < 20; i += 1, sp = speedAfter('<', sp)) slowest = sp;
    const ladder = [];
    for (let sp = slowest, i = 0; sp != null && i < 20; i += 1) {
      ladder.push(sp);
      sp = speedAfter('>', sp);
    }
    const offList = { from: 3, faster: speedAfter('>', 3), slower: speedAfter('<', 3) };

    // 3. keys handled by a view, not by the global handler
    const step = (mods, state = {}, el = null) => pitInLapsKeyStep({ key: ']', ...mods, getModifierState: () => false }, state, el);
    const cmdBar = fs.readFileSync(path.join(SRC, 'components/CommandPalette/CommandBar.jsx'), 'utf8');
    const slashFocus = /if \(e\.key !== '\/'\) return;[\s\S]{0,400}inputRef\.current\?\.focus\(\)/.test(cmdBar);
    const local = [
      {
        keys: ['[', ']'],
        view: 'Circle of Doom (CircleOfDoom.jsx, while it is on screen)',
        effect: '"pit in k laps": one lap fewer / one lap more',
        rule: `plain key ${step({}) === 1 ? 'steps' : 'does not step'}; with AltGr (Ctrl+Alt, layouts that type [ with it) ${step({ ctrlKey: true, altKey: true }) === 1 ? 'steps' : 'does not step'}; with Ctrl alone ${step({ ctrlKey: true }) ? 'steps' : 'does not step'}; with Cmd ${step({ metaKey: true }) ? 'steps' : 'does not step'}; in a text field ${step({}, {}, { tagName: 'INPUT' }) ? 'steps' : 'does not step'}; with the palette or the cheatsheet open ${step({}, { cheatsheetOpen: true }) ? 'steps' : 'does not step'}`,
      },
      {
        keys: ['/'],
        view: 'Command bar (CommandBar.jsx)',
        effect: slashFocus ? 'put the cursor in the command bar\'s search field' : '(not found in CommandBar.jsx)',
        rule: `the global handler ${describe(h.probe(k('/'))) ? 'acts on it' : 'leaves it to the command bar'}; not while an input, a textarea or an editable element has the focus, nor with the palette or the cheatsheet open`,
      },
    ];

    // 4. the cheatsheet rows against the handler
    const cheatsheet = [];
    for (const section of cheatsheetSections()) {
      for (const s of section.shortcuts) {
        const combosOf = cheatsheetCombos(s.keys);
        const effects = combosOf.map((c) => describe(h.probe(c))
          || (local.some((l) => l.keys.includes(c.key)) ? 'left to a view (below)' : 'nothing'));
        cheatsheet.push({ section: section.title, keys: s.keys.join(' '), desc: s.desc, handler: effects.join(' / ') });
      }
    }
    // keys with an effect that the cheatsheet does not list. A listed letter
    // covers its Shift form when both do the same (the handler reads 't' and
    // 'T' alike), and Ctrl covers Cmd (the cheatsheet writes the platform's key)
    const listed = new Set(cheatsheet.flatMap((r) => cheatsheetCombos(r.keys.split(' ')).map(comboName)));
    const covered = (name, keys) => listed.has(name)
      || (/^Shift\+[A-Z]$/.test(name) && keys.includes(name.slice(6)) && listed.has(name.slice(6)))
      || (name.startsWith('Cmd+') && listed.has(`Ctrl+${name.slice(4)}`));
    const unlisted = rows.flatMap((r) => r.keys.filter((n) => !covered(n, r.keys)).map((n) => ({ key: n, effect: r.effect })));

    // 5. the palette's shortcut labels against the handler
    const palette = [];
    for (const cmd of createCommandRegistry()) {
      if (!cmd.shortcut) continue;
      const combo = comboOfLabel(cmd.shortcut);
      const viaKey = h.probe(combo);
      let viaPalette;
      if (cmd.action) viaPalette = h.record(() => cmd.action());
      else viaPalette = { calls: [], events: [], set: { commandPaletteOpen: true, _paletteInitialCommand: cmd.id } };
      const same = effectKey(viaKey) === effectKey(viaPalette);
      palette.push({
        id: cmd.id,
        label: cmd.label,
        shortcut: cmd.shortcut,
        key: comboName(combo),
        palette: describe(viaPalette) || (cmd.getSubCommands ? `open its list (${cmd.id})` : 'nothing'),
        handler: describe(viaKey) || 'nothing',
        same,
      });
    }
    return { rows, conditions, ladder, offList, local, cheatsheet, unlisted, palette };
  } finally {
    h.restore();
  }
}

/** The markdown block of docs/SHORTCUTS.md (and the evidence file). */
export function renderMarkdown(rep = shortcutsReport()) {
  const L = [];
  L.push('### Global keys (src/hooks/useKeyboardShortcuts.js)');
  L.push('');
  L.push('Each key was sent to the handler during a replay of a 2024 race at lap 10 of 53, 1x, with a focus driver (LEC), two drivers selected (LEC, SAI), another driver under the pointer (SAI), the compare pair LEC / SAI in compare mode and one floating window open and tiled. Keys with the same effect share a row; a key not listed does nothing.');
  L.push('');
  L.push('| Keys | Effect |');
  L.push('|------|--------|');
  for (const r of rep.rows) L.push(`| ${r.keys.map(code).join(', ')} | ${r.effect} |`);
  L.push('');
  L.push('### When a key does something else');
  L.push('');
  L.push('| Key | When | Effect |');
  L.push('|-----|------|--------|');
  for (const c of rep.conditions) L.push(`| ${code(c.name)} | ${c.when} | ${c.effect} |`);
  L.push('');
  const sx = (v) => (v == null ? 'nothing' : `${v}x`);
  const off = rep.offList;
  L.push(`Playback speeds (\`<\` and \`>\` step through them, no wrap): ${rep.ladder.map(sx).join(', ')}. From ${sx(off.from)}, a speed not in the list, \`>\` goes to ${sx(off.faster)} and \`<\` to ${sx(off.slower)}.`);
  L.push('');
  L.push('### Keys handled by a view');
  L.push('');
  L.push('| Keys | View | Effect | Rule |');
  L.push('|------|------|--------|------|');
  for (const l of rep.local) L.push(`| ${l.keys.map(code).join(' ')} | ${l.view} | ${l.effect} | ${l.rule} |`);
  L.push('');
  L.push('### The cheatsheet (`?`) against the handler');
  L.push('');
  L.push('| Section | Keys | Cheatsheet says | The handler does |');
  L.push('|---------|------|-----------------|------------------|');
  for (const r of rep.cheatsheet) L.push(`| ${r.section} | ${code(r.keys)} | ${r.desc} | ${r.handler} |`);
  L.push('');
  if (rep.unlisted.length) {
    L.push('Keys with an effect that the cheatsheet does not list:');
    L.push('');
    for (const u of rep.unlisted) L.push(`- ${code(u.key)}: ${u.effect}`);
  } else {
    L.push('Every key with an effect is listed in the cheatsheet.');
  }
  L.push('');
  L.push('### Shortcut labels of the command palette against the handler');
  L.push('');
  L.push('The palette (Ctrl/Cmd+K) shows a key label next to some commands; running the command and pressing the key are compared on the same state.');
  L.push('');
  L.push('| Command | Label | Running the command | Pressing the key | Same effect |');
  L.push('|---------|-------|---------------------|------------------|-------------|');
  for (const p of rep.palette) {
    L.push(`| ${p.label} (\`${p.id}\`) | ${code(p.shortcut)} | ${p.palette} | ${p.handler} | ${p.same ? 'yes' : '**no**'} |`);
  }
  const differ = rep.palette.filter((p) => !p.same);
  L.push('');
  L.push(`${rep.palette.length} labelled commands, ${differ.length} whose label names a key that does something else${differ.length ? `: ${differ.map((p) => code(p.id)).join(', ')}` : ''}.`);
  return L.join('\n');
}

/** The generated block of a markdown document, or null without markers. */
export function blockOf(doc) {
  const i = doc.indexOf(BLOCK_START);
  const j = doc.indexOf(BLOCK_END);
  if (i < 0 || j < i) return null;
  return doc.slice(i + BLOCK_START.length, j).trim();
}

function main(argv) {
  const md = renderMarkdown();
  process.stdout.write(`${md}\n`);
  const outIdx = argv.indexOf('--out');
  const out = outIdx >= 0 && argv[outIdx + 1] ? path.resolve(argv[outIdx + 1]) : EVIDENCE;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${md}\n`);
  if (argv.includes('--write')) {
    const doc = fs.readFileSync(DOC, 'utf8');
    const i = doc.indexOf(BLOCK_START);
    const j = doc.indexOf(BLOCK_END);
    if (i < 0 || j < i) throw new Error(`markers not found in ${DOC}`);
    fs.writeFileSync(DOC, `${doc.slice(0, i + BLOCK_START.length)}\n\n${md}\n\n${doc.slice(j)}`);
    process.stderr.write(`wrote the generated block of ${DOC}\n`);
  }
}

