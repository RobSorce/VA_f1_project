#!/usr/bin/env node
/**
 * Coordination matrix of the dashboard's views, read from the code.
 *
 * Every link between two views goes through the Zustand store
 * (src/store/useF1Store.js): a view WRITES a coordination field when it calls
 * a store action that assigns it (or sets it with useF1Store.setState), and
 * READS it when it subscribes to it with a useF1Store selector (so it redraws
 * when the field changes). A read inside an event handler (getState().x) is
 * not a subscription and is not counted.
 *
 * How the store is read: each top-level key of the store object is a block;
 * an action's block assigns the fields written as `field:` keys (set({...}),
 * returned partial states), plus the fields of the store actions it calls
 * (get().action(), s.action()), transitively. A getter (get*) reads the
 * fields it references.
 *
 * Usage (from frontend/):
 *   node scripts/coordination_matrix.mjs                 print the markdown
 *   node scripts/coordination_matrix.mjs --out <file>    also save it to <file>
 *   node scripts/coordination_matrix.mjs --write         replace the generated block of docs/COORDINATION_GRAPH.md
 *
 * The test __tests__/coordination.matrix.test.js checks that the block in
 * docs/COORDINATION_GRAPH.md equals this script's output.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const FRONTEND = path.resolve(HERE, '..');
export const SRC = path.join(FRONTEND, 'src');
export const DOC = path.resolve(FRONTEND, '../docs/COORDINATION_GRAPH.md');
export const BLOCK_START = '<!-- coordination-matrix:start (generated by frontend/scripts/coordination_matrix.mjs; do not edit by hand) -->';
export const BLOCK_END = '<!-- coordination-matrix:end -->';

/** The store fields that link views (selection, focus, highlight, lap range), with what they hold. */
export const COORDINATION_FIELDS = Object.freeze({
  selectedDrivers: 'the drivers selected (multi-select)',
  highlightedDriver: 'the driver under the pointer (hover)',
  focusDriver: 'the focus driver (one at a time)',
  watchedRivals: 'the focus driver\'s watched rivals',
  lapDeltaBaseDriver: 'the baseline driver of the Lap Delta chart',
  compareDrivers: 'the two drivers of the Driver Comparison',
  comparisonDriver: 'the rival of the Sector Delta Waterfall and the Undercut Calculator',
  selectedLapRange: 'the one lap range (a brush, the sheet bar, a stint, a pit window, a race event), equal to brushLapRange',
  brushLapRange: 'the same lap range, under the name the Position Tracker, the Timing Sheet and Tyre Degradation read',
  selectedPCAPoints: 'the (driver, race) rows lassoed or clicked on the PCA biplot',
  pcaStrategyAnalysis: 'the backend analysis of that PCA selection (fetchPCAAnalysis)',
  selectedStint: 'the stint clicked on a tyre view',
  highlightedCompound: 'the compound highlighted on a tyre view',
  trackProgress: 'the playhead along the lap (0-1) of the speed trace',
});

/**
 * Session lifecycle actions: they clear or prime the selection for another
 * session (or the live feed), they do not link one view to another, so a
 * component calling them is not counted as a writer.
 */
export const LIFECYCLE_ACTIONS = Object.freeze(['loadSession', 'resetSession', 'enterLiveMode', 'exitLiveMode']);

/**
 * Replay-clock actions: they move the clock and re-ask what depends on it
 * (the PCA selection's analysis at the new clock), they do not link one view
 * to another either; the clock is the timeline's, not a coordination field.
 */
export const CLOCK_ACTIONS = Object.freeze(['setCurrentFrameIndex', 'setCurrentLap', 'showRaceOver', '_scheduleClockRecompute']);
const NOT_LINKS = [...LIFECYCLE_ACTIONS, ...CLOCK_ACTIONS];

/** Views drawn in the compact emitter x receiver matrix (the analysis views). */
export const MATRIX_VIEWS = Object.freeze([
  'Leaderboard', 'TrackMap', 'LapTimeChart', 'PositionByLap', 'StrategyTimeline', 'TireDegradation',
  'PCABiplot', 'PCAAnalysisPanel', 'StrategyAnalysis', 'RaceSituationMap', 'CircleOfDoom', 'RacePaceGrid',
  'LapDeltaChart', 'TelemetryStrip', 'TimelinePlayer',
]);

const FIELD_NAMES = Object.keys(COORDINATION_FIELDS);
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** The text inside the balanced parentheses that open at `open` (the index of '('). */
function balanced(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '(') depth += 1;
    else if (c === ')') {
      depth -= 1;
      if (depth === 0) return text.slice(open + 1, i);
    }
  }
  return text.slice(open + 1);
}

/** Line comments and block comments removed (a comment naming a field is not code). */
function stripComments(text) {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
}

/**
 * The store's top-level keys: for each action the coordination fields it
 * writes (transitively through the actions it calls), for each getter the
 * fields it reads.
 *
 * @param {string} storeSrc - src/store/useF1Store.js
 * @returns {{actions: Map<string, Set<string>>, getters: Map<string, Set<string>>, state: Set<string>}}
 */
export function readStore(storeSrc) {
  const start = storeSrc.indexOf('create(');
  const body = stripComments(storeSrc.slice(start));
  const lines = body.split('\n');
  const blocks = [];
  for (const line of lines) {
    const m = /^ {2}([A-Za-z_$][\w$]*)\s*:/.exec(line);
    if (m) blocks.push({ name: m[1], lines: [line] });
    else if (blocks.length) blocks[blocks.length - 1].lines.push(line);
  }
  const direct = new Map();
  const calls = new Map();
  const getters = new Map();
  const state = new Set();
  for (const b of blocks) {
    const text = b.lines.join('\n');
    const head = b.lines[0];
    const isFn = /=>|function|async/.test(head.slice(head.indexOf(':') + 1, head.indexOf(':') + 60));
    if (!isFn) { state.add(b.name); continue; }
    const rest = text.slice(text.indexOf(':') + 1);
    // Keys assigned inside the action's set( ... ) calls (object or callback)
    const setArgs = [...rest.matchAll(/\bset\s*\(/g)].map((m) => balanced(rest, m.index + m[0].length - 1)).join('\n');
    const sets = new Set(FIELD_NAMES.filter((f) => new RegExp(`(^|[\\s{,(])${escapeRe(f)}\\s*:`, 'm').test(setArgs)));
    direct.set(b.name, sets);
    calls.set(b.name, new Set([...rest.matchAll(/(?:get\(\)|\bs|\bstate)\.([A-Za-z_$][\w$]*)\s*\(/g)].map((m) => m[1])));
    if (/^get[A-Z]/.test(b.name)) {
      getters.set(b.name, new Set(FIELD_NAMES.filter((f) => new RegExp(`\\.${escapeRe(f)}\\b`).test(rest))));
    }
  }
  // Transitive closure over the actions an action calls
  const actions = new Map([...direct].map(([k, v]) => [k, new Set(v)]));
  let changed = true;
  while (changed) {
    changed = false;
    for (const [name, called] of calls) {
      const mine = actions.get(name);
      for (const c of called) {
        if (c === name || !actions.has(c) || getters.has(c) || NOT_LINKS.includes(c)) continue;
        for (const f of actions.get(c)) if (!mine.has(f)) { mine.add(f); changed = true; }
      }
    }
  }
  for (const g of getters.keys()) actions.delete(g);
  for (const a of NOT_LINKS) actions.delete(a);
  return { actions, getters, state };
}

/** Every .js / .jsx file under dir, sorted. */
function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (/\.(jsx?|mjs)$/.test(e.name)) out.push(p);
  }
  return out.sort();
}

/**
 * Is the local name `local` called (local(...)) or handed on as a callback
 * (onClick={local}, f(local), { cb: local })? A dependency-array entry is not.
 */
function isInvoked(text, local) {
  const id = escapeRe(local);
  return new RegExp(`(^|[^\\w$.])${id}\\s*\\(`).test(text)
    || new RegExp(`[={(:]\\s*${id}\\s*[})]`).test(text)
    || new RegExp(`\\(\\s*${id}\\s*,`).test(text);
}

/**
 * The coordination fields one source file writes and subscribes to.
 *
 * @param {string} source - file text
 * @param {ReturnType<typeof readStore>} store
 * @returns {{reads: Set<string>, writes: Set<string>, via: Map<string, Set<string>>}}
 *   via: field -> the store actions (or setState) the file writes it with
 */
export function scanSource(source, store) {
  const text = stripComments(source);
  const reads = new Set();
  const writes = new Set();
  const via = new Map();
  const write = (field, how) => {
    writes.add(field);
    if (!via.has(field)) via.set(field, new Set());
    via.get(field).add(how);
  };
  const useAction = (name) => {
    for (const f of store.actions.get(name) || []) write(f, name);
  };
  // Subscriptions: the argument of every useF1Store( ... ) call. An action
  // taken from the store this way (const setX = useF1Store((s) => s.setX))
  // writes only when the file calls it or hands it on as a handler
  // (onClick={setX}): one that is only listed in a dependency array writes
  // nothing.
  for (const m of text.matchAll(/useF1Store\s*\(/g)) {
    const arg = balanced(text, m.index + m[0].length - 1);
    const bound = /(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*$/.exec(text.slice(Math.max(0, m.index - 120), m.index));
    for (const n of arg.matchAll(/\.([A-Za-z_$][\w$]*)/g)) {
      const name = n[1];
      if (FIELD_NAMES.includes(name)) reads.add(name);
      else if (store.getters.has(name)) for (const f of store.getters.get(name)) reads.add(f);
      else if (store.actions.has(name) && (!bound || isInvoked(text, bound[1]))) useAction(name);
    }
  }
  // Actions called from handlers: getState().x(, state.x(, s.x(, and destructured getState()
  for (const m of text.matchAll(/(?:getState\(\)|\bstate|\bs|\bst)\.([A-Za-z_$][\w$]*)\s*\(/g)) {
    if (store.actions.has(m[1])) useAction(m[1]);
  }
  for (const m of text.matchAll(/(?:const|let)\s*\{([^}]*)\}\s*=\s*(?:useF1Store\.)?getState\(\)/g)) {
    for (const n of m[1].split(',').map((x) => x.trim().split(':')[0].trim())) {
      if (store.actions.has(n)) useAction(n);
    }
  }
  // Direct writes
  for (const m of text.matchAll(/useF1Store\.setState\(\s*\{([^}]*)\}/g)) {
    for (const f of FIELD_NAMES) if (new RegExp(`(^|[\\s{,])${escapeRe(f)}\\s*:`).test(m[1])) write(f, 'setState');
  }
  return { reads, writes, via };
}

/**
 * The coordination of every component and hook under src/components and src/hooks.
 *
 * @param {string} [srcDir]
 * @returns {{views: Object<string, {file: string, reads: string[], writes: string[], via: Object<string, string[]>}>,
 *   fields: Array<{field: string, meaning: string, writers: string[], readers: string[]}>}}
 */
export function coordinationOf(srcDir = SRC) {
  const store = readStore(fs.readFileSync(path.join(srcDir, 'store/useF1Store.js'), 'utf8'));
  const files = [...walk(path.join(srcDir, 'components')), ...walk(path.join(srcDir, 'hooks'))];
  const views = {};
  for (const file of files) {
    const name = path.basename(file).replace(/\.(jsx?|mjs)$/, '');
    const r = scanSource(fs.readFileSync(file, 'utf8'), store);
    if (!r.reads.size && !r.writes.size) continue;
    views[name] = {
      file: path.relative(srcDir, file).split(path.sep).join('/'),
      reads: [...r.reads].sort(),
      writes: [...r.writes].sort(),
      via: Object.fromEntries([...r.via].map(([f, s]) => [f, [...s].sort()]).sort()),
    };
  }
  const fields = FIELD_NAMES.map((field) => ({
    field,
    meaning: COORDINATION_FIELDS[field],
    writers: Object.keys(views).filter((v) => views[v].writes.includes(field)).sort(),
    readers: Object.keys(views).filter((v) => views[v].reads.includes(field)).sort(),
  }));
  return { views, fields };
}

const code = (s) => `\`${s}\``;
const list = (xs) => (xs.length ? xs.join(', ') : '—');

/** The generated markdown block (without the markers). */
export function renderMarkdown({ views, fields }) {
  const out = [];
  out.push('### Coordination fields: who writes, who subscribes');
  out.push('');
  out.push('| Field | Holds | Written by | Subscribed by |');
  out.push('|-------|-------|------------|---------------|');
  for (const f of fields) {
    out.push(`| ${code(f.field)} | ${f.meaning} | ${list(f.writers)} | ${list(f.readers)} |`);
  }
  out.push('');
  out.push('### Analysis views: emitter (row) -> receiver (column)');
  out.push('');
  out.push('A cell lists the fields the row view writes and the column view subscribes to.');
  out.push('');
  const present = MATRIX_VIEWS.filter((v) => views[v]);
  out.push(`| Emitter \\ Receiver | ${present.join(' | ')} |`);
  out.push(`|---|${present.map(() => '---').join('|')}|`);
  for (const a of present) {
    const cells = present.map((b) => {
      if (a === b) return '·';
      const shared = views[a].writes.filter((f) => views[b].reads.includes(f));
      return shared.length ? shared.map(code).join(' ') : '—';
    });
    out.push(`| **${a}** | ${cells.join(' | ')} |`);
  }
  out.push('');
  out.push('### Analysis views linked both ways');
  out.push('');
  out.push('| View A | View B | A -> B | B -> A |');
  out.push('|--------|--------|--------|--------|');
  for (let i = 0; i < present.length; i++) {
    for (let j = i + 1; j < present.length; j++) {
      const a = present[i];
      const b = present[j];
      const ab = views[a].writes.filter((f) => views[b].reads.includes(f));
      const ba = views[b].writes.filter((f) => views[a].reads.includes(f));
      if (ab.length && ba.length) out.push(`| ${a} | ${b} | ${ab.map(code).join(' ')} | ${ba.map(code).join(' ')} |`);
    }
  }
  return out.join('\n');
}

/** The generated block of a markdown document, or null without markers. */
export function blockOf(doc) {
  const i = doc.indexOf(BLOCK_START);
  const j = doc.indexOf(BLOCK_END);
  if (i < 0 || j < i) return null;
  return doc.slice(i + BLOCK_START.length, j).trim();
}

function main(argv) {
  const md = renderMarkdown(coordinationOf(SRC));
  process.stdout.write(`${md}\n`);
  const outIdx = argv.indexOf('--out');
  if (outIdx >= 0 && argv[outIdx + 1]) fs.writeFileSync(path.resolve(argv[outIdx + 1]), `${md}\n`);
  if (argv.includes('--write')) {
    const doc = fs.readFileSync(DOC, 'utf8');
    const i = doc.indexOf(BLOCK_START);
    const j = doc.indexOf(BLOCK_END);
    if (i < 0 || j < i) throw new Error(`markers not found in ${DOC}`);
    fs.writeFileSync(DOC, `${doc.slice(0, i + BLOCK_START.length)}\n\n${md}\n\n${doc.slice(j)}`);
    process.stderr.write(`wrote the generated block of ${DOC}\n`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main(process.argv.slice(2));
}
